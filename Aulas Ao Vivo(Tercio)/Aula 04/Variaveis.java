public class Variaveis {
    public static void main(String[] args){
        // 2 formas para declarar variavel
        System.out.println("Aula iniciada!!");
        int anoNasc = 1980;
        double peso;
        peso = 65.7;
        // esse l e f definem o tipo de dado que a variavel pode armazenar e como vai ser tratado pelo java
        long populacao = 200000L;
        float altura = 1.75f;
        // o f por exemplo informa que queremos float não double
        char sexo;
        boolean canhoto;

        // +. -. *, / e % = operadores aritmetricos
        // !, || e &&; Negação, OU e E
        System.out.println("Variaveis declaradas!");
    }  
}
